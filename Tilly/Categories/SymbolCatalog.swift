    /// Every entry, in catalogue order.
    static let all: [SymbolEntry] = sections.flatMap(\.entries)

    /// Every entry whose name components or words start with each word of `query`, ignoring case
    /// and diacritics, in catalogue order. Empty or blank `query` returns every entry.
    static func search(_ query: String) -> [SymbolEntry] {
        let tokens = query.split(whereSeparator: \.isWhitespace).map { fold(String($0)) }
        guard !tokens.isEmpty else { return all }
        return all.filter { entry in
            let candidates = candidateWords(entry)
            return tokens.allSatisfy { token in candidates.contains { $0.hasPrefix(token) } }
        }
    }

    // MARK: Private

    private static func section(_ title: String, _ rows: [(String, String)]) -> SymbolSection {
        SymbolSection(title: title, entries: rows.map { name, words in
            SymbolEntry(name: name, words: words.split(separator: " ").map(String.init))
        })
    }

    static func candidateWords(_ entry: SymbolEntry) -> [String] {
        entry.name.split(separator: ".").map { fold(String($0)) } + entry.words.map(fold)
    }

    static func fold(_ text: String) -> String {
        text.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil)
    }
}
